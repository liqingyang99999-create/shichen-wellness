import {spawnSync} from 'node:child_process';
import {mkdtemp,cp,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const branch=process.argv[2]||'main';
if(!['main','care-preview'].includes(branch))throw Error('Choose main or care-preview.');
const stage=await mkdtemp(join(tmpdir(),'shichen-1.0-pages-'));
await cp(join(root,'dist'),join(stage,'public'),{recursive:true});
await writeFile(join(stage,'wrangler.jsonc'),JSON.stringify({name:'shichen-wellness',pages_build_output_dir:'./public',compatibility_date:'2026-11-05',services:[{binding:'SHICHEN_API',service:'shichen-wellness'}]},null,2));
const result=spawnSync(process.execPath,[join(root,'node_modules/wrangler/bin/wrangler.js'),'pages','deploy','public','--project-name','shichen-wellness','--branch',branch],{cwd:stage,stdio:'inherit'});
process.exit(result.status??1);
